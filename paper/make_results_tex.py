"""Generate the paper's result numbers, Table I and loss figures from outputs/.

Run after train.py:
    python paper/make_results_tex.py
Writes paper/results_macros.tex, paper/table1.tex and paper/figures/fig4_val_loss.png,
fig5_train_loss.png, so every number in the paper comes straight from the experiment output.
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT, PAPER = ROOT / "outputs", Path(__file__).resolve().parent
NAMES = {"bilstm": "BiLSTM + GloVe", "bigru": "BiGRU + GloVe", "gru": "GRU + GloVe", "lstm": "LSTM + GloVe"}
MACRO = {"bilstm": "Bilstm", "bigru": "Bigru", "gru": "Gru", "lstm": "Lstm"}

summary = json.loads((OUT / "results.json").read_text())
runs = [json.loads(l) for l in (OUT / "runs.jsonl").read_text().splitlines()]
hist = json.loads((OUT / "history_bilstm.json").read_text())
abl = [json.loads(l) for l in (ROOT / "experiments/ablation/ablation_results.jsonl").read_text().splitlines()]

lines = ["% Auto-generated by make_results_tex.py -- do not edit by hand"]
def macro(name, value):
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

for v, s in summary.items():
    p = MACRO[v]
    macro(f"acc{p}", f"{s['accuracy_mean']*100:.2f}")
    macro(f"accsd{p}", f"{s['accuracy_sd']*100:.2f}")
    macro(f"accmin{p}", f"{s['accuracy_min']*100:.2f}")
    macro(f"accmax{p}", f"{s['accuracy_max']*100:.2f}")
    macro(f"prec{p}", f"{s['precision_mean']:.4f}")
    macro(f"rec{p}", f"{s['recall_mean']:.4f}")
    macro(f"fone{p}", f"{s['f1_mean']:.4f}")
    macro(f"nseeds{p}", str(s["n_seeds"]))

main = next(r for r in runs if r["model"] == "bilstm" and r["seed"] == 42)
best = int(np.argmin(hist["val_loss"]))
macro("valLossStart", f"{hist['val_loss'][0]:.4f}")
macro("valLossBest", f"{hist['val_loss'][best]:.4f}")
macro("bestEpoch", str(best + 1))
macro("epochsRun", str(len(hist["loss"])))
macro("mainAcc", f"{main['test']['accuracy']*100:.2f}")
tn, fp = main["test"]["confusion"][0]; fn, tp = main["test"]["confusion"][1]
macro("cmTN", tn); macro("cmFP", fp); macro("cmFN", fn); macro("cmTP", tp)
macro("testN", tn + fp + fn + tp)

ta = np.array([r["test"]["acc"] for r in abl])
base = np.array([r["test"]["acc"] for r in abl if r["cfg"] == {}])
macro("ablN", len(abl))
macro("ablMin", f"{ta.min()*100:.2f}")
macro("ablMax", f"{ta.max()*100:.2f}")
macro("ablBaseMean", f"{base.mean()*100:.2f}")
macro("ablBaseSd", f"{base.std(ddof=1)*100:.2f}")
macro("ablBaseN", len(base))
(PAPER / "results_macros.tex").write_text("\n".join(lines) + "\n")

rows = []
for v in ["bilstm", "bigru", "gru", "lstm"]:
    s = summary[v]
    rows.append(f"{NAMES[v]} & {s['accuracy_mean']*100:.2f} $\\pm$ {s['accuracy_sd']*100:.2f} & "
                f"{s['precision_mean']:.4f} & {s['recall_mean']:.4f} & {s['f1_mean']:.4f} \\\\")
(PAPER / "table1.tex").write_text(
    "\\begin{table}[!t]\n\\centering\n\\caption{Model Evaluation Metrics}\n\\label{tab:metrics}\n"
    "\\footnotesize\n\\begin{tabular}{lcccc}\n\\toprule\n"
    "\\textbf{Model} & \\textbf{Accuracy (\\%)} & \\textbf{Precision} & \\textbf{Recall} & \\textbf{F1 Score} \\\\\n\\midrule\n"
    + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\n\\vspace{2pt}\n"
    "\\parbox{0.95\\columnwidth}{\\scriptsize Held-out test set ($n=" + str(tn + fp + fn + tp) + "$). "
    "Mean over " + str(summary['bilstm']['n_seeds']) + " random seeds; accuracy shown as mean $\\pm$ standard deviation.}\n"
    "\\end{table}\n")

for key, fname, title, color in [("val_loss", "fig4_val_loss.png", "Validation Loss", "#e69f00"),
                                 ("loss", "fig5_train_loss.png", "Training Loss", "#1f77b4")]:
    fig, ax = plt.subplots(figsize=(4.6, 3.2))
    ep = range(1, len(hist[key]) + 1)
    ax.plot(ep, hist[key], color=color, marker="o", ms=3, label=title)
    if key == "val_loss":
        ax.axvline(best + 1, ls="--", c="grey", lw=1, label=f"best epoch ({best + 1})")
    ax.set_title(title); ax.set_xlabel("Epoch"); ax.set_ylabel("Loss"); ax.legend(fontsize=8); ax.grid(alpha=.3)
    fig.tight_layout(); fig.savefig(PAPER / "figures" / fname, dpi=200); plt.close(fig)
print("wrote results_macros.tex, table1.tex, fig4/fig5")
